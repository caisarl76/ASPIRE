r"""Derive ASPIRE's torso-rooted G1 kinematic models from the GR00T-WholeBodyControl fork.

Two outputs, both mesh-free so they need no mesh directory:

* ``g1_upper_body.xml``: the SONIC MuJoCo full body with the pelvis freejoint and
  both leg subtrees removed, every mesh geom and mesh asset dropped, and a
  ``{side}_grasp_site`` added under each wrist-yaw link. Actuators and sensors
  are dropped with the legs: this model is a kinematic tree for mink, nothing
  is simulated on it.
* ``g1_dual_arm.urdf``: the fork's dual-arm URDF with mesh visuals/collisions
  stripped and a fixed ``{side}_grasp`` link at the same offset as the site.

Usage:
    python scripts/build_g1_models.py --fork ~/work/GR00T-WholeBodyControl \\
        --out src/cap_harness/g1_real/description
"""

from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

MJCF_SRC = "gear_sonic_deploy/g1/g1_29dof_with_hand.xml"
URDF_SRC = "gear_sonic/data/robots/g1/g1_dual_arm.urdf"
GRASP_XYZ = "0.19 0 0"
SIDES = ("left", "right")


def _provenance(src: str) -> str:
    return (
        f"<!-- GENERATED by scripts/build_g1_models.py from {src} "
        "(GR00T-WholeBodyControl fork). Do not edit by hand; rerun the generator. -->\n"
    )


def _parent_map(root: ET.Element) -> dict[ET.Element, ET.Element]:
    return {child: parent for parent in root.iter() for child in parent}


def _remove(root: ET.Element, elements: list[ET.Element]) -> None:
    parents = _parent_map(root)
    for element in elements:
        parents[element].remove(element)


def build_mjcf(source: Path) -> str:
    root = ET.parse(source).getroot()

    legs = [b for b in root.iter("body") if b.get("name", "").endswith("hip_pitch_link")]
    _remove(root, legs)
    _remove(root, [j for j in root.iter("joint") if j.get("type") == "free"])
    _remove(root, [g for g in root.iter("geom") if g.get("type") == "mesh"])
    _remove(root, list(root.iter("mesh")))
    _remove(root, [s for s in root if s.tag in ("actuator", "sensor")])
    for asset in root.findall("asset"):
        if len(asset) == 0:
            root.remove(asset)

    bodies = {b.get("name"): b for b in root.iter("body")}
    for side in SIDES:
        ET.SubElement(
            bodies[f"{side}_wrist_yaw_link"],
            "site",
            name=f"{side}_grasp_site",
            pos=GRASP_XYZ,
            quat="1 0 0 0",
        )

    ET.indent(root)
    return _provenance(MJCF_SRC) + ET.tostring(root, encoding="unicode") + "\n"


def build_urdf(source: Path) -> str:
    root = ET.parse(source).getroot()

    _remove(
        root,
        [
            shape
            for tag in ("visual", "collision")
            for shape in root.iter(tag)
            if shape.find("geometry/mesh") is not None
        ],
    )

    for side in SIDES:
        ET.SubElement(root, "link", name=f"{side}_grasp")
        joint = ET.SubElement(root, "joint", name=f"{side}_grasp_joint", type="fixed")
        ET.SubElement(joint, "origin", xyz=GRASP_XYZ, rpy="0 0 0")
        ET.SubElement(joint, "parent", link=f"{side}_wrist_yaw_link")
        ET.SubElement(joint, "child", link=f"{side}_grasp")

    ET.indent(root)
    return _provenance(URDF_SRC) + ET.tostring(root, encoding="unicode") + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fork", type=Path, required=True, help="GR00T-WholeBodyControl checkout")
    parser.add_argument("--out", type=Path, required=True, help="output directory")
    args = parser.parse_args()

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "g1_upper_body.xml").write_text(build_mjcf(args.fork / MJCF_SRC))
    (args.out / "g1_dual_arm.urdf").write_text(build_urdf(args.fork / URDF_SRC))


if __name__ == "__main__":
    main()
