"""Whole-body posture and arm-to-leg clearance for the G1, from SONIC's joint feedback.

Uses ``description/g1_full_body.xml`` (every link a fitted capsule or box, pelvis fixed;
generated by scripts/build_g1_models.py). Positions are in the torso frame. The palm
normal is taken from the direction the fingers close in the model, so it holds for both
hands without per-side constants.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import mujoco
import numpy as np

FULL_BODY_XML = Path(__file__).parent / "description" / "g1_full_body.xml"
SIDES = ("left", "right")
PALM_FROM_WRIST_M = 0.11  # palm center along the wrist-yaw axis (both hand types)
PALM_SURFACE_M = 0.02  # palm face out from the axis, along the normal


def _subtree(model: mujoco.MjModel, root: str) -> set[int]:
    top = model.body(root).id
    out = set()
    for body in range(model.nbody):
        parent = body
        while parent not in (0, top):
            parent = model.body_parentid[parent]
        if parent == top:
            out.add(body)
    return out


class G1Posture:
    """Forward kinematics of the whole body and the arm-to-leg distances."""

    def __init__(
        self,
        hand_joint_names: Mapping[str, Sequence[str]],
        hand_closed: Mapping[str, Sequence[float]],
        path: Path = FULL_BODY_XML,
    ) -> None:
        self.model = mujoco.MjModel.from_xml_path(str(path))
        self.data = mujoco.MjData(self.model)
        m = self.model
        hinges = [j for j in range(m.njnt) if m.jnt_type[j] == mujoco.mjtJoint.mjJNT_HINGE]
        self._body_qpos = np.array(
            [m.jnt_qposadr[j] for j in hinges if "_hand_" not in m.joint(j).name]
        )
        self._hand_qpos = {
            side: np.array([m.jnt_qposadr[m.joint(name).id] for name in hand_joint_names[side]])
            for side in SIDES
        }
        if self._body_qpos.size != 29:
            raise ValueError(f"expected 29 body joints in {path}, found {self._body_qpos.size}")
        legs = (
            _subtree(m, "left_hip_pitch_link")
            | _subtree(m, "right_hip_pitch_link")
            | {m.body("pelvis").id}
        )
        self._leg_geoms = [
            g for g in range(m.ngeom) if m.geom_bodyid[g] in legs and m.geom_size[g][0] > 0.01
        ]
        self._arm_geoms = {
            side: [
                g for g in range(m.ngeom) if m.geom_bodyid[g] in _subtree(m, f"{side}_elbow_link")
            ]
            for side in SIDES
        }
        self._normal_local = {side: self._palm_normal(side, hand_closed[side]) for side in SIDES}
        self._fromto = np.zeros(6)

    def _palm_normal(self, side: str, closed: Sequence[float]) -> np.ndarray:
        """Wrist-frame palm normal: where the index finger moves when the hand closes."""
        wrist, index = (
            self.model.body(f"{side}_wrist_yaw_link").id,
            self.model.body(f"{side}_hand_index_1_link").id,
        )
        tips = []
        for q in (np.zeros(len(closed)), np.asarray(closed, float)):
            self.data.qpos[:] = 0.0
            self.data.qpos[self._hand_qpos[side]] = q
            mujoco.mj_kinematics(self.model, self.data)
            rotation = self.data.xmat[wrist].reshape(3, 3)
            tips.append(rotation.T @ (self.data.xpos[index] - self.data.xpos[wrist]))
        move = tips[1] - tips[0]
        move[0] = 0.0  # across the palm, not along the fingers
        return move / np.linalg.norm(move)

    def set_state(
        self, body_q: Sequence[float], hands: Mapping[str, Sequence[float]] | None = None
    ) -> None:
        """SONIC's 29 body joints (MuJoCo order) and optionally both hands (profile order)."""
        self.data.qpos[:] = 0.0
        self.data.qpos[self._body_qpos] = np.asarray(body_q, float).reshape(29)
        for side, q in (hands or {}).items():
            self.data.qpos[self._hand_qpos[side]] = np.asarray(q, float).reshape(-1)
        mujoco.mj_kinematics(self.model, self.data)

    def set_arms(
        self, arms: Mapping[str, Sequence[float]], arm_qpos: Mapping[str, np.ndarray]
    ) -> None:
        """Override arm joints on top of the last state (for checking trajectory waypoints)."""
        for side, q in arms.items():
            self.data.qpos[arm_qpos[side]] = np.asarray(q, float).reshape(-1)
        mujoco.mj_kinematics(self.model, self.data)

    def arm_qpos(self, joint_names: Mapping[str, Sequence[str]]) -> dict[str, np.ndarray]:
        return {
            side: np.array([self.model.jnt_qposadr[self.model.joint(n).id] for n in names])
            for side, names in joint_names.items()
        }

    def leg_clearance(self, side: str) -> tuple[float, str, str]:
        """Smallest distance from this forearm and hand to the legs and pelvis (m), and the pair."""
        best, pair = np.inf, ("", "")
        for a in self._arm_geoms[side]:
            for b in self._leg_geoms:
                d = mujoco.mj_geomDistance(self.model, self.data, a, b, 0.5, self._fromto)
                if d < best:
                    best, pair = d, (self.model.geom(a).name, self.model.geom(b).name)
        return float(best), *pair

    def _torso(self, point: np.ndarray) -> list[float]:
        torso = self.model.body("torso_link").id
        rotation = self.data.xmat[torso].reshape(3, 3)
        return (rotation.T @ (point - self.data.xpos[torso])).round(4).tolist()

    def _direction(self, vector: np.ndarray) -> list[float]:
        rotation = self.data.xmat[self.model.body("torso_link").id].reshape(3, 3)
        return (rotation.T @ vector).round(4).tolist()

    def summary(self) -> dict[str, Any]:
        """Landmarks (torso frame), palm frame, and arm-to-leg clearance for the last state."""
        m, d = self.model, self.data
        position = lambda body: d.xpos[m.body(body).id]
        out: dict[str, Any] = {"frame": "torso"}
        for side in SIDES:
            wrist = m.body(f"{side}_wrist_yaw_link").id
            rotation = d.xmat[wrist].reshape(3, 3)
            normal = rotation @ self._normal_local[side]
            palm = d.xpos[wrist] + rotation[:, 0] * PALM_FROM_WRIST_M + normal * PALM_SURFACE_M
            clearance, arm_geom, leg_geom = self.leg_clearance(side)
            out[side] = {
                "shoulder": self._torso(position(f"{side}_shoulder_pitch_link")),
                "elbow": self._torso(position(f"{side}_elbow_link")),
                "wrist": self._torso(d.xpos[wrist]),
                "palm_center": self._torso(palm),
                "palm_normal": self._direction(normal),
                "finger_direction": self._direction(rotation[:, 0]),
                "leg_clearance_m": round(clearance, 4),
                "closest": [arm_geom.removesuffix("_fit"), leg_geom.removesuffix("_fit")],
            }
            out[f"{side}_leg"] = {
                joint: self._torso(position(f"{side}_{body}_link"))
                for joint, body in (
                    ("hip", "hip_pitch"),
                    ("knee", "knee"),
                    ("ankle", "ankle_pitch"),
                )
            }
        out["pelvis"] = self._torso(position("pelvis"))
        return out


__all__ = ["FULL_BODY_XML", "G1Posture"]
